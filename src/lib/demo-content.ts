export function filterDemoArticles(category: Category, query: string) {
  const normalized = query
    .trim()
    .toLocaleLowerCase("ru-RU")
    .replaceAll("ё", "е");
  return demoArticles.filter((article) => {
    const matchesCategory =
      category === "Все новости" || article.category === category;
    const searchable = `${article.title} ${article.excerpt} ${article.category}`
      .toLocaleLowerCase("ru-RU")
      .replaceAll("ё", "е");
    return matchesCategory && (!normalized || searchable.includes(normalized));
  });
}
